end package body iterative_round_pkg;

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use work.iterative_round_pkg.all;

entity iterative_round is 
  port(
    clk        : in  std_logic;
    reset      : in  std_logic;

    -- current 64-bit state coming from state register / previous stage
    X_in       : in  std_logic_vector(63 downto 0);

    -- roundkeys table (generated by scheduler / ROM)
    rk_words   : in  rk_array;

    -- which round index this cycle corresponds to (i = 1..prelast typically)
    --rk_idx     : in  std_logic_vector(5 downto 0);
    

    -- enable from FSM (HIGH during the intermediate rounds window)
    encrypt_en : in  std_logic;
    key_mode   : in std_logic;

    r_cnt      : in  unsigned(4 downto 0); 

    X_after    : out std_logic_vector(63 downto 0)
  
  );
end entity iterative_round;

architecture rtl of iterative_round is

  component function_f_new is
    port (
      data_in  : in  std_logic_vector(15 downto 0);
      data_out : out std_logic_vector(15 downto 0)
    );
  end component;

  component rp is
    port(
      X      : in  std_logic_vector(63 downto 0);
      rp_out : out std_logic_vector(63 downto 0)
    );
  end component;

  -- split state
  signal x0, x1, x2, x3 : std_logic_vector(15 downto 0);

  -- F outputs
  signal f_x0, f_x2 : std_logic_vector(15 downto 0);

  -- selected roundkeys for this round
  signal rk0, rk1 : std_logic_vector(15 downto 0);

  -- datapath
  signal x1_new, x3_new : std_logic_vector(15 downto 0);
  signal x_before_rp    : std_logic_vector(63 downto 0);
  signal x_after_rp     : std_logic_vector(63 downto 0);

  -- registered output
  signal x_after_reg    : std_logic_vector(63 downto 0);

begin

  -- split X_in: X0|X1|X2|X3
  x0 <= X_in(63 downto 48);
  x1 <= X_in(47 downto 32);
  x2 <= X_in(31 downto 16);
  x3 <= X_in(15 downto 0);

  -- choose roundkeys for this round
  -- (You can change mapping if your key schedule uses different indices.)
  rk0 <= rk_words(0);
  rk1 <= rk_words(1);

  -- F functions (iterative round does NOT do pre-whitening)
  U_F1 : function_f_new port map(data_in => x0, data_out => f_x0);
  U_F2 : function_f_new port map(data_in => x2, data_out => f_x2);

  -- update X1 and X3 (same structure as in the algorithm)
  x1_new <= std_logic_vector(unsigned(x1) xor unsigned(f_x0) xor unsigned(rk0));
  x3_new <= std_logic_vector(unsigned(x3) xor unsigned(f_x2) xor unsigned(rk1));

  -- bundle + rp
  x_before_rp <= x0 & x1_new & x2 & x3_new;
  U_RP : rp port map(X => x_before_rp, rp_out => x_after_rp);

  -- register when enabled (every intermediate round cycle)
  process(clk)
begin
  if rising_edge(clk) then
    if reset = '1' then
      x_after_reg <= (others => '0');
    
    elsif (encrypt_en = '1') and
         (r_cnt) >= 1 and
         (r_cnt) < 24 and key_mode='0' then

        x_after_reg <= x_after_rp;
    
    elsif (encrypt_en = '1') and
         (r_cnt) >= 1 and
         (r_cnt) < 29 and key_mode='1' then

        x_after_reg <= x_after_rp;

     end if;
  end if;
end process;

X_after <= x_after_reg;

end architecture;
